def load_video_frames(
    video_dir: str,
    num_frames: int = 16,
    frame_size: int = 512,
) -> tuple:
    """
    Load N evenly-spaced JPEG frames from one video folder.

    Parameters
    ----------
    video_dir  : path to the video folder  (e.g. .../JPEGImages/0a2f2bd294)
    num_frames : N frames to sample (paper uses 16)
    frame_size : resize each frame to (frame_size, frame_size)
                 512 → matches paper exactly (32×32 feature map)
                 224 → faster sanity check (14×14 feature map)

    Returns
    -------
    tensor : torch.FloatTensor  shape (1, 3, N, H, W),  values ∈ [-1, 1]
    paths  : list[str]  — selected file paths (for visualisation)
    """
    all_paths = sorted(glob.glob(os.path.join(video_dir, "*.jpg")))
    if not all_paths:
        raise FileNotFoundError(f"No .jpg files in: {video_dir}")

    # Evenly-spaced indices (with repetition if video is shorter than num_frames)
    indices  = np.linspace(0, len(all_paths) - 1, num_frames, dtype=int)
    selected = [all_paths[i] for i in indices]

    frames = []
    for path in selected:
        img = Image.open(path).convert("RGB")
        img = img.resize((frame_size, frame_size), Image.BILINEAR)
        arr = np.array(img, dtype=np.float32) / 255.0   # [0, 1]
        arr = arr * 2.0 - 1.0                            # [-1, 1]  I3D pre-training norm
        frames.append(arr)                               # (H, W, 3)

    video = np.stack(frames)             # (N, H, W, 3)
    video = video.transpose(3, 0, 1, 2) # (3, N, H, W)
    tensor = torch.from_numpy(video).unsqueeze(0)  # (1, 3, N, H, W)

    print(f"Loaded {num_frames}/{len(all_paths)} frames from '{os.path.basename(video_dir)}'")
    print(f"  Files selected : {[os.path.basename(p) for p in selected]}")
    print(f"  Tensor shape   : {tensor.shape}   dtype={tensor.dtype}")
    return tensor, selected

