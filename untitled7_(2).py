"""# Decoder — Decoding with Dynamic Filters

Implements Section 3.3 of Gavrilyuk et al. (CVPR 2018).

**Plain-English summary of what this block does:**
The textual encoder gave us one 300-dim vector that *describes* the actor/action.
The decoder turns that description into three little "stamps" (called *dynamic
filters*) and presses each stamp onto the video feature map. Wherever the stamp
matches the video, we get a bright spot — that's the segmentation.

We do this at three zoom levels (32×32, 128×128, 512×512) so the model gets both
coarse location and fine detail. The biggest one (512×512) is the final mask.

We build it in four small pieces so each can be tested on its own:

| Piece | Class | Input → Output |
|-------|-------|----------------|
| 1 | `DynamicFilterGenerator` | sentence `(B,300)` → 3 filters |
| 2 | `DeconvBlock`            | feature map → ×4 bigger feature map |
| 3 | `Decoder`               | filters + video feat → 3 response maps |
| 4 | `ActorActionSegmenter`  | glues text + video + decoder together |

**One channel-count note (important):** the paper draws the 32×32 filter as
`1×1×832`. But *your* `VideoEncoder` appends 2 coordinate channels, so its output
is **834** channels, not 832. The filter must match whatever the feature actually
has — so we use **834** for the 32×32 level. The other two levels (256, 128) come
out of the deconv blocks and match the paper exactly.

"""

# ---------------------------------------------------------------------------
# DECODER CELL 1 — DynamicFilterGenerator
#
# Paper (Sec 3.3, Eq. 1):
#   f_r = tanh(W_r · T + b_r)
#   "we generate dynamic filters for several resolutions with different
#    network parameters."  + "better results with a tanh activation."
#
# One Linear layer per resolution. Each produces a 1-D filter whose length
# equals the channel count of the video feature at that resolution.
# ---------------------------------------------------------------------------

class DynamicFilterGenerator(nn.Module):
    """
    Sentence vector  ->  three dynamic filters (one per resolution).

    Input
    -----
    T : (B, 300)   sentence vector from the TextualEncoder

    Output
    ------
    dict with keys 32, 128, 512:
        filters[32]  : (B, ch_32)    convolved with the 32x32  video feature
        filters[128] : (B, ch_128)   convolved with the 128x128 video feature
        filters[512] : (B, ch_512)   convolved with the 512x512 video feature

    Why a dict keyed by resolution?
        Keeps the wiring explicit and readable — when the Decoder asks for
        "the filter for the 128 map" there is no ambiguity.
    """

    def __init__(self, text_dim: int = 300,
                 ch_32: int = 834, ch_128: int = 256, ch_512: int = 128):
        super().__init__()
        # ch_32 = 834 because VideoEncoder appends 2 coord channels to 832.
        self.fc_32  = nn.Linear(text_dim, ch_32)
        self.fc_128 = nn.Linear(text_dim, ch_128)
        self.fc_512 = nn.Linear(text_dim, ch_512)

    def forward(self, T: torch.Tensor) -> dict:
        # tanh squashes each filter weight into [-1, 1]  (paper's choice)
        return {
            32:  torch.tanh(self.fc_32(T)),    # (B, 834)
            128: torch.tanh(self.fc_128(T)),   # (B, 256)
            512: torch.tanh(self.fc_512(T)),   # (B, 128)
        }

# ---------------------------------------------------------------------------
# DECODER CELL 2 — DeconvBlock
#
# Paper (Sec 3.3, Details):
#   "Each of our deconvolutional networks consists of two blocks with one
#    deconvolutional layer with kernel size 8x8 and stride 4, followed by a
#    convolutional layer with a kernel size of 3x3 and a stride of 1."
#
#   Crucial detail: deconv is applied to the VIDEO FEATURE, not the response
#   map. "Different from [6, 15], who apply deconvolution on the segmentation
#    response maps, we use the deconvolutional layers on the video
#    representation V_r directly."
#
# One DeconvBlock = upsample x4 (32->128 or 128->512).
#   ConvTranspose2d(k=8, s=4, padding=2) gives an EXACT x4 size increase.
#   (output = (in-1)*stride - 2*pad + kernel = (32-1)*4 - 4 + 8 = 128 ✓)
# ---------------------------------------------------------------------------

class DeconvBlock(nn.Module):
    """
    Upsample a video feature map by exactly 4x in height and width.

    in_ch  channels  ->  out_ch channels
    H x W            ->  4H x 4W

    Example: (B, 834, 32, 32) -> (B, 256, 128, 128)
    """

    def __init__(self, in_ch: int, out_ch: int):
        super().__init__()
        # Upsample x4. padding=2 with k=8,s=4 lands on a clean 4x multiple.
        self.deconv = nn.ConvTranspose2d(in_ch, out_ch,
                                         kernel_size=8, stride=4, padding=2)
        # Refine, keep the size (k=3, s=1, padding=1 preserves H,W).
        self.conv = nn.Conv2d(out_ch, out_ch, kernel_size=3, stride=1, padding=1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = F.relu(self.deconv(x))   # (B, out_ch, 4H, 4W)
        x = F.relu(self.conv(x))     # same size, refined
        return x

# ---------------------------------------------------------------------------
# DECODER CELL 3 — dynamic convolution helper + Decoder
#
# Paper (Sec 3.3, Eq. 2):   S_r = f_r * V_r
#   The dynamic filter is 1x1 spatially, so "convolving" it with the video
#   feature is just a per-pixel dot product across the channel axis:
#       response(i,j) = sum_c  filter[c] * video[c, i, j]
#   We implement it with a broadcasted multiply + channel sum. This handles a
#   *different* filter per batch sample (which a normal nn.Conv2d cannot).
# ---------------------------------------------------------------------------

def dynamic_conv(feature: torch.Tensor, filt: torch.Tensor) -> torch.Tensor:
    """
    Per-sample 1x1 dynamic convolution.

    feature : (B, C, H, W)   video feature at some resolution
    filt    : (B, C)         dynamic filter for that resolution (one per sample)

    returns : (B, 1, H, W)   response (segmentation logits at that resolution)
    """
    # filt[:, :, None, None] -> (B, C, 1, 1) so it broadcasts over H, W.
    return (feature * filt[:, :, None, None]).sum(dim=1, keepdim=True)


class Decoder(nn.Module):
    """
    Decoder — Gavrilyuk et al. CVPR 2018, Section 3.3.

    Inputs
    ------
    T          : (B, 300)          sentence vector  (TextualEncoder output)
    video_feat : (B, 834, 32, 32)  video feature    (VideoEncoder output)

    Output
    ------
    dict of response maps (raw logits, NOT yet sigmoid-ed):
        32  : (B, 1, 32,  32)
        128 : (B, 1, 128, 128)
        512 : (B, 1, 512, 512)   <- final segmentation mask

    Flow (matches Figure 2, left-to-right):
        video_feat (834ch, 32)  --filter32-->  response 32
                  |
              deconv1 (834->256, x4)
                  v
        video_feat (256ch, 128) --filter128--> response 128
                  |
              deconv2 (256->128, x4)
                  v
        video_feat (128ch, 512) --filter512--> response 512  (final)
    """

    def __init__(self, text_dim: int = 300, video_ch: int = 834):
        super().__init__()
        self.filters = DynamicFilterGenerator(
            text_dim=text_dim, ch_32=video_ch, ch_128=256, ch_512=128)
        self.deconv1 = DeconvBlock(in_ch=video_ch, out_ch=256)   # 32  -> 128
        self.deconv2 = DeconvBlock(in_ch=256,      out_ch=128)   # 128 -> 512

    def forward(self, T: torch.Tensor, video_feat: torch.Tensor) -> dict:
        f = self.filters(T)   # dict: {32: (B,834), 128: (B,256), 512: (B,128)}

        # --- 32x32: filter the raw video feature directly ---
        v32 = video_feat                       # (B, 834, 32, 32)
        s32 = dynamic_conv(v32, f[32])         # (B, 1, 32, 32)

        # --- 128x128: deconv the video feature, then filter ---
        v128 = self.deconv1(v32)               # (B, 256, 128, 128)
        s128 = dynamic_conv(v128, f[128])      # (B, 1, 128, 128)

        # --- 512x512: deconv again, then filter -> final mask ---
        v512 = self.deconv2(v128)              # (B, 128, 512, 512)
        s512 = dynamic_conv(v512, f[512])      # (B, 1, 512, 512)

        return {32: s32, 128: s128, 512: s512}

# ---------------------------------------------------------------------------
# DECODER CELL 4 — ActorActionSegmenter  (the full model)
#
# Wires the three components together exactly as in handoff.md Step 2.
#   text_encoder  : TextualEncoder   (already defined above)
#   video_encoder : VideoEncoder     (already defined above)
#   decoder       : Decoder          (defined in DECODER CELL 3)
# ---------------------------------------------------------------------------

class ActorActionSegmenter(nn.Module):
    """
    Full end-to-end model: (video, sentence_embedding) -> 3 response maps.

    forward inputs
    --------------
    video              : (B, 3, N, 512, 512)   N RGB frames, values in [-1, 1]
    sentence_embedding : (B, max_len, 300)     padded word2vec matrices

    forward output
    --------------
    dict {32, 128, 512} of response maps (logits). Use [512] as the mask.
    """

    def __init__(self, text_encoder: nn.Module,
                 video_encoder: nn.Module,
                 decoder: nn.Module):
        super().__init__()
        self.text_encoder  = text_encoder
        self.video_encoder = video_encoder
        self.decoder       = decoder

    def forward(self, video: torch.Tensor,
                sentence_embedding: torch.Tensor) -> dict:
        text_feat  = self.text_encoder(sentence_embedding)   # (B, 300)
        video_feat = self.video_encoder(video)               # (B, 834, 32, 32)
        masks      = self.decoder(text_feat, video_feat)     # 3 response maps
        return masks

# ---------------------------------------------------------------------------
# DECODER CELL 5 — Multi-resolution logistic loss
#
# Paper (Sec 3.4, Eqs. 3-5):
#   L      = sum_r  alpha_r * L_r          (alpha_r = 1 for r in {32,128,512})
#   L_r    = mean over pixels of L_r_ij
#   L_r_ij = log(1 + exp(-S_r_ij * Y_r_ij))   (logistic loss)
#
# Y_r_ij is +1 for actor/action pixels, -1 for background.
# We get the lower-res ground truths by downsampling the 512 mask.
# ---------------------------------------------------------------------------

def make_multiscale_targets(mask_512: torch.Tensor) -> dict:
    """
    Build {32, 128, 512} ground-truth masks from one 512x512 binary mask.

    mask_512 : (B, 1, 512, 512)  with values in {0, 1}

    returns  : dict of (B, 1, r, r) tensors with values in {-1, +1}
               (+1 = actor/action, -1 = background) as the paper's loss needs.
    """
    targets = {}
    for r in (32, 128, 512):
        m = F.interpolate(mask_512, size=(r, r), mode="nearest")  # (B,1,r,r) in {0,1}
        targets[r] = m * 2.0 - 1.0                                # {0,1} -> {-1,+1}
    return targets


def multiresolution_loss(responses: dict, targets: dict,
                         alphas: dict = None) -> torch.Tensor:
    """
    responses : dict {32,128,512} of (B,1,r,r) raw logits (model output)
    targets   : dict {32,128,512} of (B,1,r,r) in {-1,+1}  (from make_multiscale_targets)
    alphas    : per-resolution weights; paper uses 1.0 for all.

    returns   : scalar loss tensor.
    """
    if alphas is None:
        alphas = {32: 1.0, 128: 1.0, 512: 1.0}

    total = 0.0
    for r in (32, 128, 512):
        S = responses[r]      # (B,1,r,r)
        Y = targets[r]        # (B,1,r,r) in {-1,+1}
        # log(1 + exp(-S*Y)) is numerically the softplus of (-S*Y).
        L_r = F.softplus(-S * Y).mean()   # mean over all pixels & batch
        total = total + alphas[r] * L_r
    return total

