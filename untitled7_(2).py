# ---------------------------------------------------------------------------
# CELL 4 — sentence_to_embedding
#
# Converts one raw sentence into a padded (max_len × 300) float matrix.
#
# Paper:
#   "Each word of the input sentence is represented as a 300-dimensional
#    word2vec embedding, without any further preprocessing.
#    Each sentence is additionally padded to have the same size."
# ---------------------------------------------------------------------------

def sentence_to_embedding(
    sentence: str,
    word2vec_model,
    max_len: int = 20, # PyTorch needs to stack them into a single tensor, which means every sentence must have the same shape
) -> torch.Tensor:
    """
    Sentence string → padded word-embedding matrix.

    Parameters
    ----------
    sentence       : raw text, e.g. "a man in dark suit standing on the back"
    word2vec_model : gensim KeyedVectors (300-dim)
    max_len        : pad or truncate to this many tokens (paper uses ~20)

 a 10-word sentence is represented by a 10 × 300 matrix
    Returns
    -------
    torch.FloatTensor  shape (max_len, 300)
        Rows beyond the sentence length are zero-padded.
        OOV words are also zero-filled.
    """
    tokens    = sentence.lower().split()
    embed_dim = word2vec_model.vector_size          # 300

    # Start with an all-zero matrix (handles both padding and OOV)
    matrix = np.zeros((max_len, embed_dim), dtype=np.float32)

    for i, token in enumerate(tokens[:max_len]):    # truncate if too long
        if token in word2vec_model:
            matrix[i] = word2vec_model[token]
        # OOV → stays as zero vector

    return torch.from_numpy(matrix)                 # (max_len, 300)

# ---------------------------------------------------------------------------
# CELL 5 — TextualEncoder  (the "Word2Vec Embedding → CNN" block in Fig. 2)
#
# Paper (Sec 3.1):
#   "The network consists of a single 1D convolutional layer with a temporal
#    filter size equal to 2 and with the same output dimension as the word2vec
#    representation. After the convolutional layer we apply the ReLU activation
#    function and perform max-pooling to obtain a representation for the whole
#    sentence."
# ---------------------------------------------------------------------------

class TextualEncoder(nn.Module):
    """
    1D-CNN sentence encoder from Gavrilyuk et al. CVPR 2018, Section 3.1.

    Architecture
    ------------
    Input  : (B, max_len, 300)  — batch of padded word-embedding matrices
                                   (produced by sentence_to_embedding)
    Step 1 : permute → (B, 300, max_len)   [Conv1D wants channels-first]
    Step 2 : Conv1D(in=300, out=300, k=2)  → (B, 300, max_len-1)
    Step 3 : ReLU
    Step 4 : global max-pool over time     → (B, 300)
    Output : (B, 300)  — one vector per sentence

    This 300-dim vector is later fed into three separate FC layers inside
    the decoder to produce dynamic convolutional filters at resolutions
    32×32 (832-ch), 128×128 (256-ch), and 512×512 (128-ch).

    NOTE: Word embeddings are created *outside* this module (frozen).
          Only the Conv1D weights are learned.
    """

    def __init__(self, embed_dim: int = 300, kernel_size: int = 2):
        super().__init__()

        # Single 1-D convolutional layer
        # kernel_size=2 means it looks at pairs of adjacent word vectors
        self.conv1d = nn.Conv1d(
            in_channels=embed_dim,    # 300  — word2vec dim
            out_channels=embed_dim,   # 300  — "same output dimension"
            kernel_size=kernel_size,  # 2    — "temporal filter size equal to 2"
            padding=0,                # no padding; max-pool handles variable len
        )
        self.relu = nn.ReLU()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        Parameters
        ----------
        x : torch.FloatTensor  shape (B, max_len, 300)

        Returns
        -------
        torch.FloatTensor  shape (B, 300)
        """
        # Conv1D in PyTorch expects (B, C_in, L), so move the channel dim first
        x = x.permute(0, 2, 1)           # (B, 300, max_len)

        x = self.conv1d(x)                # (B, 300, max_len - 1)
        x = self.relu(x)                  # (B, 300, max_len - 1)

        # Global max-pool over the time dimension → fixed-size sentence vector
        x = x.max(dim=-1).values          # (B, 300)

        return x

# ---------------------------------------------------------------------------
# CELL 6 — encode_sentence  (convenience wrapper for inference)
# ---------------------------------------------------------------------------

def encode_sentence(
    sentence: str,
    word2vec_model,
    encoder: TextualEncoder,
    max_len: int = 20,
) -> torch.Tensor:
    """
    End-to-end helper: raw sentence → 300-dim feature vector.

    Parameters
    ----------
    sentence       : e.g. "a man in dark suit standing on the back"
    word2vec_model : loaded gensim KeyedVectors
    encoder        : TextualEncoder instance (can be on CPU or GPU)
    max_len        : same value used during training

    Returns
    -------
    torch.FloatTensor  shape (300,)
    """
    # Derive the device from the encoder's parameters
    enc_device = next(encoder.parameters()).device

    emb   = sentence_to_embedding(sentence, word2vec_model, max_len)  # (L, 300)
    emb   = emb.unsqueeze(0).to(enc_device)                           # (1, L, 300)

    encoder.eval()
    with torch.no_grad():
        feat = encoder(emb)   # (1, 300)

    return feat.squeeze(0)    # (300,)

