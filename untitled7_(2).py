# ---------------------------------------------------------------------------
# CELL 5 (FIXED) — VideoEncoder
#
# The forward() now manually steps through each I3D layer and stops
# at mixed_4f — giving (B, 832, T', H', W') as required by the paper.
# ---------------------------------------------------------------------------

class VideoEncoder(nn.Module):
    """
    Video Encoder — Gavrilyuk et al. CVPR 2018, Section 3.2.

    Architecture (Figure 2 — the red-circled Video Encoder block):

        (B, 3, N, 512, 512)
            ↓  I3D layers up to mixed_4f (manually stepped)
        (B, 832, T', 32, 32)    T'≈4 for N=16  |  32×32 for 512×512 input
            ↓  avg-pool over T'
        (B, 832, 32, 32)
            ↓  L2-normalise per spatial position (over channel dim)
        (B, 832, 32, 32)
            ↓  append (y, x) coordinate grids
        (B, 834, 32, 32)

    Why mixed_4f?
        4 spatial halvings before it:  512 → 256 → 128 → 64 → 32
        832 output channels match the dynamic filter size in the decoder.
    Video Encoder — Gavrilyuk et al. CVPR 2018, Section 3.2.

    Uses a forward hook on Mixed_4f to capture (B, 832, T', H', W'),
    then applies avg-pool → L2-norm → spatial coords.

    This approach is naming-convention agnostic: it searches the model's
    module tree for the Mixed_4f InceptionModule, so it works regardless
    of which pytorch-i3d fork or version you cloned.
    """

    def __init__(self, i3d: InceptionI3d):
        super().__init__()
        self.i3d   = i3d
        self._feat = {}          # hook writes here; forward reads here

        # --- Find mixed_4f and attach hook ---
        target_module, target_name = self._find_mixed4f(i3d)
        self._hook = target_module.register_forward_hook(
            lambda m, inp, out: self._feat.update({'mixed_4f': out})
        )
        print(f"VideoEncoder: hooked '{target_name}'  "
              f"(type={type(target_module).__name__})")

    # ------------------------------------------------------------------
    # Layer search
    # ------------------------------------------------------------------

    @staticmethod
    def _find_mixed4f(i3d: nn.Module):
        """
        Search the module tree for mixed_4f using three strategies:

        Strategy 1 — exact attribute match (covers most pytorch-i3d versions)
            self.mixed_4f  or  self.Mixed_4f

        Strategy 2 — named_modules() substring match
            Matches any module whose dotted name contains 'mixed_4f'
            (case-insensitive), e.g. 'inception_i3d/Mixed_4f'

        Strategy 3 — output channel count (fallback, fragile)
            The 13th InceptionModule in traversal order is mixed_4f.
            Only used if strategies 1 & 2 both fail.

        Raises RuntimeError with a helpful dump if nothing found.
        """
        # Strategy 1: direct attribute
        for attr_name in ('mixed_4f', 'Mixed_4f'):
            if hasattr(i3d, attr_name):
                return getattr(i3d, attr_name), attr_name

        # Strategy 2: substring search through named_modules
        for name, mod in i3d.named_modules():
            normalised = name.lower().replace('/', '_').replace('-', '_')
            if 'mixed_4f' in normalised:
                return mod, name

        # Strategy 3: count InceptionModules (mixed_4f is the 5th one)
        #   3b, 3c, 4b, 4c, 4d, 4e → mixed_4f is the 6th inception block
        inception_count = 0
        for name, mod in i3d.named_modules():
            if type(mod).__name__ == 'InceptionModule':
                inception_count += 1
                if inception_count == 6:            # 3b=1, 3c=2, 4b=3, 4c=4, 4d=5... wait
                    return mod, f"{name} (strategy-3 fallback)"

        # Nothing found — dump the tree so the user can report back
        all_names = [n for n, _ in i3d.named_modules() if n]
        raise RuntimeError(
            "Could not locate Mixed_4f in the I3D model.\n"
            f"All module names:\n" + "\n".join(f"  {n}" for n in all_names)
        )

    # ------------------------------------------------------------------
    # Spatial coordinate helper
    # ------------------------------------------------------------------

    @staticmethod
    def _append_spatial_coords(x: torch.Tensor) -> torch.Tensor:
        """
        Append y-grid and x-grid as 2 extra channels.  Values ∈ [-1, 1].
        Paper (Sec 3.2): "allows learning spatial qualifiers like 'left of'."
        """
        B, C, H, W = x.shape
        y_line = torch.linspace(-1, 1, H, device=x.device)
        x_line = torch.linspace(-1, 1, W, device=x.device)
        gy, gx = torch.meshgrid(y_line, x_line, indexing="ij")
        gy = gy.unsqueeze(0).unsqueeze(0).expand(B, -1, -1, -1)
        gx = gx.unsqueeze(0).unsqueeze(0).expand(B, -1, -1, -1)
        return torch.cat([x, gy, gx], dim=1)

    # ------------------------------------------------------------------
    # Forward
    # ------------------------------------------------------------------

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        Args:
            x : (B, 3, N, H, W)  values ∈ [-1, 1]
        Returns:
            (B, 834, H', W')   H'=W'=32 for 512×512 input
        """
        self._feat.clear()

        # Run full I3D forward; the hook captures Mixed_4f output mid-way
        _ = self.i3d(x)

        feat = self._feat['mixed_4f']       # (B, 832, T', H', W')
        feat = feat.mean(dim=2)             # avg-pool over T'   → (B, 832, H', W')
        feat = F.normalize(feat, p=2, dim=1)                     # L2-norm per position
        feat = self._append_spatial_coords(feat)                 # (B, 834, H', W')
        return feat

    def __del__(self):
        """Clean up the hook when the encoder is garbage-collected."""
        if hasattr(self, '_hook'):
            self._hook.remove()

