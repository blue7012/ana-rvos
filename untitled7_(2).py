"""# Real Loss — Section 3.4, with Ground-Truth Annotations

The earlier prediction cell used a *random* mask, so its loss was meaningless.
Now we have real annotations, so we can compute the actual training loss.

**What Section 3.4 needs (Eqs. 3-5):**

```
L       = Σ_r  α_r · L_r            α_r = 1  for r ∈ {32, 128, 512}
L_r     = (1/r²) Σ_i Σ_j  L_r_ij           ← mean over the r×r pixels
L_r_ij  = log(1 + exp(−S_r_ij · Y_r_ij))   ← logistic loss
```

- `S_r_ij` = our model's response value at pixel (i,j), resolution r  (the logits)
- `Y_r_ij` = ground-truth label: **+1** actor/action pixel, **−1** background

**Two facts that decide how we read the annotation:**

1. *Which frame?* Section 3.4: the ground truth is "the frame in the **middle**
   of each input video clip." We segment the middle frame, so we load the mask
   for that one frame only.

2. *What format?* Your `Annotations/0a2f2bd294/00000.png ...` are YouTube-VOS
   **palette PNGs**: each pixel stores a class *index* (0 = background, 1,2,…
   = object instances). The red colour you see is just the palette — the real
   value is the index. So "actor pixel" = `index > 0`. We read the index map
   directly (`np.array(Image.open(...))`), **not** the RGB colours.

"""

# ---------------------------------------------------------------------------
# REAL-LOSS CELL 1 — load_annotation_mask
#
# Reads ONE YouTube-VOS palette-PNG annotation and returns a binary mask
# tensor (1, 1, 512, 512) with values in {0, 1}.
#
#   index 0   -> background -> 0
#   index >=1 -> any object -> 1   (actor/action)
#
# We read the raw palette indices (np.array on a 'P'-mode image), NOT RGB.
# ---------------------------------------------------------------------------

def load_annotation_mask(anno_path: str, size: int = 512) -> torch.Tensor:
    """
    Load one annotation PNG -> binary mask tensor.

    Parameters
    ----------
    anno_path : path to a single mask PNG, e.g.
                ".../Annotations/0a2f2bd294/00045.png"
    size      : resize the mask to (size, size). 512 = paper-accurate.

    Returns
    -------
    torch.FloatTensor  (1, 1, size, size)  values in {0, 1}
    """
    m = Image.open(anno_path)            # 'P' mode: pixel values are class indices
    idx = np.array(m)                    # (H, W) ints; 0=bg, >=1=object
    binary = (idx > 0).astype(np.float32)  # any object -> 1, background -> 0

    t = torch.from_numpy(binary)[None, None]   # (1, 1, H, W)
    # nearest-neighbour so we never invent fractional labels between 0 and 1
    t = F.interpolate(t, size=(size, size), mode="nearest")
    return t


def middle_frame_anno_path(anno_video_dir: str, frame_paths: list) -> str:
    """
    Pick the annotation PNG that matches the MIDDLE sampled video frame.

    The video frame files and the annotation files share the same names
    (00045.jpg  <->  00045.png), so we take the middle frame_path, swap the
    folder and the extension.

    Parameters
    ----------
    anno_video_dir : ".../Annotations/0a2f2bd294"
    frame_paths    : list of sampled JPEG paths from load_video_frames()
    """
    mid_jpg = frame_paths[len(frame_paths) // 2]          # e.g. ".../00045.jpg"
    stem    = os.path.splitext(os.path.basename(mid_jpg))[0]  # "00045"
    return os.path.join(anno_video_dir, stem + ".png")

